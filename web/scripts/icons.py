"""The new app's icons: Lucide (lucide.dev, ISC licence), one line-icon set for the whole app.

Only the icons the app uses are copied, into web/src/generated/icons.js ({name: the SVG's inner shapes}), so there
is no icon package to download and nothing unused is shipped. Run it with a Lucide checkout (its icons/ folder):

    git clone --depth 1 --branch 1.70.0 https://github.com/lucide-icons/lucide /tmp/lucide
    python web/scripts/icons.py /tmp/lucide/icons

It finds the names in web/src: every <Icon n="name" …/> must be a Lucide icon (else it stops), and any other
string literal in a file that uses Icon is taken when Lucide has an icon of that name (names chosen in code, such as
n={open ? "chevron-up" : "chevron-down"} or a map of alert types to icons).
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(os.path.dirname(HERE), "src")
OUT = os.path.join(SRC, "generated", "icons.js")
VERSION = "1.70.0"


def wanted(folder: str) -> set[str]:
    names = set()
    known = {f[:-4] for f in os.listdir(folder) if f.endswith(".svg")}
    pat = re.compile(r'\bn="([a-z0-9-]+)"')
    for root, _, files in os.walk(SRC):
        if "generated" in root:
            continue
        for f in files:
            if f.endswith((".js", ".jsx")):
                text = open(os.path.join(root, f), encoding="utf-8").read()
                names.update(pat.findall(text))
                if "Icon" in text:
                    names.update(n for n in re.findall(r'"([a-z0-9-]+)"', text) if n in known)
    return names


def main(folder: str) -> None:
    out = {}
    missing = []
    for name in sorted(wanted(folder)):
        path = os.path.join(folder, name + ".svg")
        if not os.path.exists(path):
            missing.append(name)
            continue
        svg = open(path, encoding="utf-8").read()
        inner = svg[svg.index(">", svg.index("<svg")) + 1: svg.rindex("</svg>")]
        out[name] = " ".join(inner.split()).replace(" />", "/>")
    if missing:
        sys.exit("Not in Lucide: " + ", ".join(missing))
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(f"// Lucide {VERSION} (lucide.dev, ISC licence, © Lucide Icons and Contributors): the icons the app uses.\n"
                 "// Generated by web/scripts/icons.py. Do not edit here.\n")
        fh.write("export default " + json.dumps(out, indent=0, ensure_ascii=False) + ";\n")
    print(len(out), "icons written")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "/tmp/lucide/icons")
