"""The classic app's interactive editors (the Lattice Group and Set editors, and the others as they move across), copied
into the new app as ES modules before each build: web/src/generated/<name>.js. They are the very same JavaScript the
classic app runs (lattice_component.py and friends), so a fix there reaches both apps. Each module exports the
component function ({data, setTriggerValue, parentElement}) and its CSS. Being under web/src, their T("…") texts are
picked up by words.py, so they are translated like the rest of the new app."""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, ROOT)
import i18n  # noqa: E402
import lattice_component as lc  # noqa: E402
import prism_component as pc  # noqa: E402
import funnel_stages_component as fsc  # noqa: E402

OUT = os.path.join(ROOT, "web", "src", "generated")
os.makedirs(OUT, exist_ok=True)
HEAD = "// Generated by web/scripts/components.py from the classic app's {src}. Do not edit here.\n/* eslint-disable */\n"


def write(name: str, js: str, css: str, src: str) -> None:
    js = i18n.js_ready(js).replace("export default function", "export function", 1)
    body = HEAD.format(src=src) + js + f"\nexport const css = {json.dumps(css)};\nexport default {js.split('export function ', 1)[1].split('(', 1)[0]};\n"
    with open(os.path.join(OUT, f"{name}.js"), "w", encoding="utf-8") as fh:
        fh.write(body)


write("lattice_group", lc.JS, lc.CSS, "lattice_component.py (JS)")
write("lattice_set", lc.SET_JS, lc.CSS, "lattice_component.py (SET_JS)")
write("prism_board", pc.JS, pc.CSS, "prism_component.py (JS)")
write("funnel_stages", fsc.JS, fsc.CSS, "funnel_stages_component.py (JS)")
print("components written")
